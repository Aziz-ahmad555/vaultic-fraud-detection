"""The E15 report, rendered from the saved final-run results (no recomputation; D188).

  python -m vaultic.stage2.report      writes research/tables/stage2/e15_report.md

Reads research/tables/stage2/e15_results.json and e15_refit_checks.json (EXP-215-final). The
primary deletion test (D121's absolute-attribution order: H6a, H6b) and the declared secondary
analysis (D167, D59's positive-attribution order, its own Holm family) are reported side by side
for MVAF and B5, each with the label it was registered under. Counterfactual validity is judged
against each system's own decision boundary, which the report states.
"""

from __future__ import annotations

import json

from vaultic.eval.bootstrap import format_p
from vaultic.paths import RESEARCH_DIR
from vaultic.stage2.e15 import SECONDARY_LABEL

OUT_DIR = RESEARCH_DIR / "tables" / "stage2"
PRIMARY_LABEL = "PRIMARY (D121, absolute-attribution order; decides H6a / H6b)"
BOUNDARY_NOTE = (
    "Counterfactual validity uses a different decision boundary for each system, so the MVAF and "
    "B5 figures are not directly comparable: an MVAF counterfactual is valid only if the "
    "transaction is no longer an alert at all, i.e. its recomputed E12 decision is allow or "
    "monitor, below the step-up threshold (D159, stricter than D121's wording); a B5 "
    "counterfactual is valid if B5's score falls below B5's frozen cost threshold (Table 1)."
)


def _ci(v: dict, digits: int = 4) -> str:
    return f"{v['mean']:.{digits}f} [{v['ci_low']:.{digits}f}, {v['ci_high']:.{digits}f}]"


def _test(t: dict) -> str:
    return (f"{t['diff']:+.4f} [{t['ci_low']:+.4f}, {t['ci_high']:+.4f}], p {format_p(t['p_value'])}, "
            f"Holm p {format_p(t['p_holm'])}")  # fmt: skip


def render_e15(results: dict, refit: dict | None = None) -> str:
    lines = ["# E15: explanation faithfulness, stability, seed consistency, counterfactuals", "",
             "Generated by `python -m vaultic.stage2.report` from the saved EXP-215-final results "
             "(research/tables/stage2/e15_results.json); pre-registered in D121 section 1, "
             "details D158-D167. Test period, frozen final-run models.", ""]  # fmt: skip
    if refit:
        v, t = refit["validation"], refit["test"]
        lines += [f"**Refit checks (D158 (4), D173, D174):** validation {'passed' if v['passed'] else 'FAILED'} "
                  f"({v['rows']:,} rows); test {'passed' if t['passed'] else 'FAILED'} ({t['rows']:,} rows: "
                  f"MVAF {t['mvaf']:.1e}, B5 {t['b5']:.1e}, anomaly scores "
                  f"{max(t['anomaly'].values()):.1e}, E12 cost {t['e12_cost']:.2f}).", ""]  # fmt: skip
    lines += ["## Deletion test (1.1): primary and secondary orderings", "",
              "AOPC per alert = mean over k = 1..10 of risk(original) - risk(top-k features at their "
              "training medians); comparators: 20 random orders and the global permutation-importance "
              "order; paired bootstrap over alerts (1,000 resamples), Holm within each family.", "",
              "| system | ordering | AOPC (attribution) | vs random | vs permutation |",
              "|---|---|---|---|---|"]  # fmt: skip
    for s in ("MVAF", "B5"):
        r = results[s]
        h = r["hypotheses"]
        key = next(k for k in r["aopc"] if k.startswith("attribution_positive_order"))
        sec = r["secondary_positive_order"]
        lines.append(f"| {s} | {PRIMARY_LABEL} | {_ci(r['aopc']['attribution'])} | "
                     f"H6a {_test(h['H6a'])}: **{'supported' if h['H6a']['supported'] else 'not supported'}** | "
                     f"H6b {_test(h['H6b'])}: **{'supported' if h['H6b']['supported'] else 'not supported'}** |")  # fmt: skip
        lines.append(f"| {s} | {sec['label']} | {_ci(r['aopc'][key])} | "
                     f"{_test(sec['tests']['positive - random'])} | "
                     f"{_test(sec['tests']['positive - permutation'])} |")  # fmt: skip
    lines += ["", f"The secondary rows carry the label \"{SECONDARY_LABEL}\" (D167): they were added "
              "after a validation check (D166) and never decide H6a or H6b. Comparator AOPCs: "
              + "; ".join(f"{s} random {_ci(results[s]['aopc']['random'])}, permutation "
                          f"{_ci(results[s]['aopc']['permutation'])}" for s in ("MVAF", "B5")) + ".", ""]  # fmt: skip

    lines += ["## Stability (1.4) and seed consistency (1.5)", "",
              "| system | x0.99 | x1.01 | x0.95 | x1.05 | top-1 changed (x0.95) | seeds (top-5 Jaccard) |",
              "|---|---|---|---|---|---|---|"]  # fmt: skip
    for s in ("MVAF", "B5"):
        st = results[s]["stability"]
        lines.append(f"| {s} | " + " | ".join(_ci(st[f]["top3_jaccard"], 3) for f in ("x0.99", "x1.01", "x0.95", "x1.05"))
                     + f" | {_ci(st['x0.95']['top1_changed'], 3)} | {_ci(results[s]['seed_consistency'], 3)} |")  # fmt: skip

    lines += ["", "## Counterfactual validity (1.6)", "", BOUNDARY_NOTE, "",
              "| system | decision boundary | validity | any valid | proximity | sparsity |",
              "|---|---|---|---|---|---|"]  # fmt: skip
    bound = {"MVAF": "E12 step-up threshold: no longer an alert (D159)",
             "B5": "B5's frozen cost threshold (Table 1)"}  # fmt: skip
    for s in ("MVAF", "B5"):
        c = results[s]["counterfactuals"]
        lines.append(f"| {s} | {bound[s]} | {_ci(c['validity'], 3)} | {_ci(c['any_valid'], 3)} | "
                     f"{_ci(c['proximity'], 2)} | {_ci(c['sparsity'], 2)} |")  # fmt: skip
    g = results["phase9_gate"]
    lines += ["", f"Search: DiCE random, varying TransactionAmt and ProductCD only (D163, D170), "
              f"setting {results['MVAF']['counterfactuals']['setting']} (D165). MVAF's looser D121 "
              f"reading (below its own action's threshold): "
              f"{_ci(results['MVAF']['counterfactuals']['loose_validity'], 3)}.", "",
              f"**Phase 9 exit gate (H6a supported for MVAF and MVAF validity > {g['validity_target']}):** "
              f"{'PASSED' if g['passed'] else 'NOT PASSED'} (H6a {'supported' if g['H6a_MVAF_supported'] else 'not supported'}, "
              f"validity {g['MVAF_validity']:.3f}).", ""]  # fmt: skip
    return "\n".join(lines)


def main() -> None:
    results = json.loads((OUT_DIR / "e15_results.json").read_text("utf-8"))
    refit_path = OUT_DIR / "e15_refit_checks.json"
    refit = json.loads(refit_path.read_text("utf-8")) if refit_path.exists() else None
    out = OUT_DIR / "e15_report.md"
    out.write_text(render_e15(results, refit), "utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
